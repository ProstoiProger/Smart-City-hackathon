const DICT: Record<Lang, Record<string, string>> = { ru, kk, en };

export type Vars = Record<string, string | number>;
export type T = (key: string, vars?: Vars) => string;

export function tr(lang: Lang, key: string, vars?: Vars): string {
  let s = DICT[lang]?.[key] ?? ru[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, String(vars[k]));
  return s;
}

export function has(key: string): boolean {
  return key in ru;
}

export function useT(): T {
  const { lang } = usePrefs();
  return (key, vars) => tr(lang, key, vars);
}

/** Number/date locale. Browsers often lack kk-KZ data and fall back to "7,431";
 * Kazakhstan uses the same grouping as ru-RU ("7 431"), so both languages use it. */
export function locale(lang: Lang): string {
  return lang === "en" ? "en-GB" : "ru-RU";
}
